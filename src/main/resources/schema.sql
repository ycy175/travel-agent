-- ============================================================
-- 差旅 Agent 平台 - P0 基础表结构
-- 说明：使用 CREATE TABLE IF NOT EXISTS，保证每次启动可重复执行。
-- 主键统一使用业务生成的字符串 ID，避免依赖自增序列，方便后续迁移 MySQL。
-- ============================================================

CREATE TABLE IF NOT EXISTS idempotency_record (
    idempotency_key VARCHAR(255) PRIMARY KEY,
    status VARCHAR(50) NOT NULL,
    result_json TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 员工账号：身份系统的唯一事实来源
CREATE TABLE IF NOT EXISTS app_user (
    id VARCHAR(64) PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(64) NOT NULL,
    employee_level VARCHAR(16) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'EMPLOYEE',
    department VARCHAR(64),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 会话：服务端持久化，前端不再把历史放在 localStorage
CREATE TABLE IF NOT EXISTS chat_session (
    id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    title VARCHAR(128) NOT NULL,
    pinned BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chat_session_user ON chat_session (user_id, pinned, updated_at);

-- 消息：用户消息与 Agent 回复都落库，刷新/换设备可恢复
CREATE TABLE IF NOT EXISTS chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(64) NOT NULL,
    role VARCHAR(16) NOT NULL,
    content CLOB NOT NULL,
    prompt_tokens INT,
    completion_tokens INT,
    cost DECIMAL(12, 6),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chat_message_session ON chat_message (session_id, id);

-- 审批单：Agent 只负责"起草"，人工确认后才进入 APPROVED
CREATE TABLE IF NOT EXISTS travel_approval (
    id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    session_id VARCHAR(64) NOT NULL,
    itinerary VARCHAR(1000) NOT NULL,
    cost DECIMAL(12, 2) NOT NULL,
    status VARCHAR(16) NOT NULL,
    reject_reason VARCHAR(500),
    approver_id VARCHAR(64),
    approved_at TIMESTAMP,
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_approval_session ON travel_approval (session_id, created_at);
CREATE INDEX IF NOT EXISTS idx_approval_user ON travel_approval (user_id, status);

-- 差旅政策：level + city 定位一条规则，city='*' 表示该职级的默认规则
CREATE TABLE IF NOT EXISTS travel_policy (
    id VARCHAR(64) PRIMARY KEY,
    employee_level VARCHAR(16) NOT NULL,
    city VARCHAR(64) NOT NULL DEFAULT '*',
    flight_class VARCHAR(16) NOT NULL DEFAULT 'ECONOMY',
    hotel_limit DECIMAL(10, 2) NOT NULL,
    daily_allowance DECIMAL(10, 2) NOT NULL,
    advance_days INT NOT NULL DEFAULT 7,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_policy_level_city ON travel_policy (employee_level, city);

-- 订单：一张审批单同一类型最多一条订单，靠唯一索引兜底幂等
CREATE TABLE IF NOT EXISTS travel_order (
    id VARCHAR(64) PRIMARY KEY,
    approval_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    type VARCHAR(16) NOT NULL,
    supplier VARCHAR(32) NOT NULL,
    supplier_order_no VARCHAR(64),
    title VARCHAR(255) NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,
    cabin_class VARCHAR(16),
    nights INT,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_order_approval_type ON travel_order (approval_id, type);
CREATE INDEX IF NOT EXISTS idx_order_user ON travel_order (user_id, created_at);

-- 审计日志：所有"人/Agent 触发的写操作"都留痕，支持追责与回放
CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64),
    session_id VARCHAR(64),
    action VARCHAR(64) NOT NULL,
    resource VARCHAR(128),
    detail CLOB,
    success BOOLEAN NOT NULL DEFAULT TRUE,
    duration_ms INT,
    ip VARCHAR(64),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_user_time ON audit_log (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_action_time ON audit_log (action, created_at);


